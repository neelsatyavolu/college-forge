import assert from 'node:assert/strict';
import puppeteer from 'puppeteer-core';
const base=process.env.BASE || 'http://127.0.0.1:3210';
const browser=await puppeteer.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true});
try {
 const page=await browser.newPage();
 page.setDefaultTimeout(20000);
 const errors=[];const aiCalls=[];
 page.on('pageerror',error=>errors.push(error.message));
 page.on('request',req=>{if(req.url().includes('/api/ai/chat')) aiCalls.push(req.url());});
 await page.goto(base+'/hub/index.html',{waitUntil:'networkidle2'});
 const click=async(text)=>page.evaluate(text=>{const el=[...document.querySelectorAll('button')].find(el=>el.textContent.includes(text));if(!el)throw Error('Missing '+text);el.click();},text);
 const fill=async(selector,value)=>page.$eval(selector,(el,value)=>{Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(el,value);el.dispatchEvent(new Event('input',{bubbles:true}));},value);
 await page.waitForSelector('.cf-page');
 await click('Set up my workspace');
 await page.waitForSelector('.cf-onboard');
 await click('Return to workspace');
 await page.waitForSelector('.cf-page');
 await click('Set up my workspace');
 await page.waitForSelector('.cf-onboard');
 await click('Continue');
 await page.waitForFunction(()=>document.body.innerText.includes('Continue without AI'));
 await click('Continue without AI');
 await page.waitForSelector('[placeholder="Alex Rivera"]');
 await fill('[placeholder="Alex Rivera"]','Onboarding browser verification');
 await fill('[placeholder="2027"]','2027');
 await fill('[placeholder="Lincoln High School"]','Verification High School');
 await fill('[placeholder="Computer Science"]','Biology');
 await fill('[placeholder="Austin, TX"]','California');
 await click('Continue');
 await page.waitForSelector('[placeholder="3.95"]');
 await fill('[placeholder="3.95"]','3.7');
 await click('Continue');
 await page.waitForFunction(()=>document.body.innerText.includes('Upload your transcript'));
 await click('Skip');
 await page.waitForSelector('.cf-onboard-textarea');
 await page.type('.cf-onboard-textarea','Library volunteer, 2 hours weekly');
 await click('Continue');
 await page.waitForFunction(()=>document.body.innerText.includes('Must-include schools'));
 await click('Continue');
 await page.waitForFunction(()=>document.body.innerText.includes('Upload documents'));
 await click('Skip');
 await page.waitForFunction(()=>document.body.innerText.includes('Review & build'));
 await click('Build my hub');
 await page.waitForSelector('.cf-page');
 const ws=await page.evaluate(async()=>{const res=await fetch('/api/workspace');if(!res.ok)throw Error('Workspace fetch failed');return res.json();});
 assert.equal(ws.onboarding.completed,true);
 assert.equal(ws.applicant.gpaUnweighted,'3.7');
 assert.equal(ws.profile.intended,'Biology');
 assert.equal(ws.onboarding.storyNotes.activities,'Library volunteer, 2 hours weekly');
 assert.ok(ws.colleges.length>0,'Fair-data list should seed without AI');
 assert.equal(aiCalls.length,0);
 await page.reload({waitUntil:'networkidle2'});
 await page.waitForSelector('.cf-page');
 const reloaded=await page.evaluate(async()=>(await fetch('/api/workspace')).json());
 assert.equal(reloaded.applicant.name,'Onboarding browser verification');
 assert.equal(reloaded.colleges.length,ws.colleges.length);
 assert.deepEqual(errors,[]);
 console.log(`PASS real no-AI onboarding, cancel navigation, ${ws.colleges.length} recommended schools, profile/story saved and retained after reload.`);
} finally {await browser.close();}
