import assert from 'node:assert/strict';
import puppeteer from 'puppeteer-core';
const base = process.env.BASE || 'http://127.0.0.1:3210';
const browser = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
try {
  const page = await browser.newPage();
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.setViewport({width:1440,height:1000});
  await page.goto(base+'/hub/index.html#recommendations',{waitUntil:'networkidle2'});
  await page.waitForSelector('.cf-recommendation-card');
  const clickText = async text => page.evaluate(text => { const button=[...document.querySelectorAll('button')].find(b=>b.textContent.trim()===text); if(!button) throw new Error('Button missing: '+text); button.click(); },text);
  await clickText('Adjust preferences');
  await page.type('.cf-preference-fields input','Computer Science');
  await page.select('.cf-preference-fields select','conservative');
  await page.evaluate(()=>[...document.querySelectorAll('fieldset label')].find(l=>l.textContent==='West').querySelector('input').click());
  await clickText('Update recommendations');
  await page.waitForFunction(()=>!document.querySelector('.cf-preference-form'));
  await page.waitForFunction(()=>document.querySelector('.cf-recommendation-intro strong')?.textContent==='Computer Science');
  const ws = await page.evaluate(()=>fetch('/api/workspace').then(r=>r.json()));
  assert.deepEqual(ws.onboarding.listPrefs.regions,['west']);
  assert.equal(ws.profile.intended,'Computer Science');
  await page.waitForSelector('.cf-recommendation-card');
  const before=await page.$eval('.cf-recommendation-card h2',e=>e.textContent);
  await page.click('.cf-recommendation-card button');
  await page.waitForFunction(()=>document.querySelector('.cf-recommendation-card button')?.textContent==='Saved ✓');
  await page.reload({waitUntil:'networkidle2'}); await page.waitForSelector('.cf-recommendation-card');
  assert.equal(await page.$eval('.cf-recommendation-card button',e=>e.textContent),'Saved ✓');
  const after=await page.evaluate(()=>fetch('/api/workspace').then(r=>r.json()));
  assert.equal(after.colleges.length,1); assert.equal(after.colleges[0].name,before);
  await clickText('Discuss with AI ✱');
  await page.waitForSelector('.cf-chat-panel');
  assert.match(await page.$eval('.cf-chat-panel input:not([type="file"])',e=>e.value),/ranking evidence/);
  await page.keyboard.press('Escape');
  await page.setViewport({width:390,height:900});
  await page.waitForFunction(()=>document.querySelector('aside').hasAttribute('inert'));
  await page.click('button[aria-label="Open navigation"]');
  await page.waitForFunction(()=>document.querySelector('aside').classList.contains('is-open') && document.querySelector('aside').getBoundingClientRect().left >= -1);
  await page.click('nav a[href="#shortlist"]');
  await page.waitForFunction(()=>document.querySelector('h1')?.textContent==='School list');
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'shortlist has no horizontal page overflow');
  assert.deepEqual(errors,[]);
  console.log('PASS recommendation preferences, saved school reload, AI prompt handoff, mobile navigation');
} finally {await browser.close();}
